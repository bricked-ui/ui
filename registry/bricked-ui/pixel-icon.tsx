export type PixelIconName = keyof typeof ICONS;

/**
 * A custom pixel grid: one string per row, `"1"` = filled pixel.
 * Any size works (built-ins are 7x7, github is 16x16). Keep rows the same
 * length — ragged rows render left-aligned against the widest row.
 */
export type PixelIconGrid = readonly string[];

/** Anything PixelIcon and the `icon` prop accept: a registry name or your own grid. */
export type PixelIconInput = PixelIconName | PixelIconGrid;

/**
 * Normalize a name-or-grid into renderable rows.
 * Unknown names resolve to `undefined` (renders nothing, never crashes).
 */
export function resolvePixelGrid(
  input: PixelIconInput | undefined | null
): readonly string[] | undefined {
  if (!input) return undefined;
  if (typeof input !== "string") return input;
  return (ICONS as Record<string, readonly string[]>)[input];
}

export function PixelIcon({
  name,
  grid,
  icon,
  size = "md",
  variant = "primary",
  className,
}: {
  /** Registry icon name. Kept for back-compat — `icon` does the same plus custom grids. */
  name?: PixelIconName;
  /** Custom pixel grid. Wins over `icon`/`name` when provided. */
  grid?: PixelIconGrid;
  /** Registry name or custom grid. Wins over `name` when provided. */
  icon?: PixelIconInput;
  size?: "sm" | "md" | "lg";
  variant?: "primary" | "dark";
  className?: string;
}) {
  const resolved =
    grid ??
    (icon !== undefined ? resolvePixelGrid(icon) : undefined) ??
    (name ? ICONS[name] : undefined);
  if (!resolved || resolved.length === 0) return null;
  const cols = Math.max(...resolved.map((r) => r.length));
  const rows = resolved.length;
  return (
    <svg
      data-size={size}
      data-variant={variant}
      className={
        "bricked-icon block shrink-0" + (className ? ` ${className}` : "")
      }
      style={{
        width: `calc(var(--icon, 4px) * ${cols})`,
        height: `calc(var(--icon, 4px) * ${rows})`,
      }}
      viewBox={`0 0 ${cols} ${rows}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {resolved.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "1" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="currentColor" />
          ) : null
        )
      )}
    </svg>
  );
}
