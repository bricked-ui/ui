export type PixelIconName = keyof typeof ICONS;

/**
 * A custom pixel grid: one string per row, `"1"` = filled pixel.
 * Any size works (7x7 glyphs, brand marks at 16x16). Keep rows the same
 * length — ragged rows render left-aligned against the widest row.
 */
export type PixelIconGrid = readonly string[];

/** Anything PixelIcon and the `icon` prop accept: a registry name or your own grid. */
export type PixelIconInput = PixelIconName | PixelIconGrid;

/**
 * Normalize a name-or-grid into renderable rows.
 * Unknown names resolve to `undefined` (renders nothing, never crashes).
 */
export function resolvePixelGrid(
  input: PixelIconInput | undefined | null
): readonly string[] | undefined {
  if (!input) return undefined;
  if (typeof input !== "string") return input;
  return (ICONS as Record<string, readonly string[]>)[input];
}
